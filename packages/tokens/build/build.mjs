/**
 * Token pipeline.
 *
 * One source of truth (JSON) → four outputs:
 *   - tokens.css      CSS custom properties, themed via [data-theme] + prefers-color-scheme
 *   - _tokens.scss    Sass variables for authoring inside components
 *   - index.ts        typed TS constants, so tokens are reachable from logic as well as styles
 *   - tokens.json     flat map for design tools and for the contrast audit
 *
 * Core tokens (palette, space, type) are theme-independent.
 * Semantic tokens (theme.*) are emitted once per theme and are the ONLY tokens
 * components are allowed to reference — see docs/adr/0002-three-layer-token-architecture.md.
 */
import StyleDictionary from 'style-dictionary';
import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const THEMES = ['light', 'dark'];
const PREFIX = 'mrd';

/** kebab-case CSS custom property names, always prefixed. */
StyleDictionary.registerTransform({
  name: 'name/mrd-kebab',
  type: 'name',
  transform: token => [PREFIX, ...token.path].join('-').toLowerCase(),
});

/** Emit `--mrd-*` declarations under a theme selector rather than :root. */
StyleDictionary.registerFormat({
  name: 'css/themed',
  format: ({ dictionary, options }) => {
    const decls = dictionary.allTokens
      .map(t => {
        const comment = t.comment ? ` /* ${t.comment} */` : '';
        return `  --${t.name}: ${t.value};${comment}`;
      })
      .join('\n');
    if (options.selector === ':root') return `:root {\n${decls}\n}\n`;
    return (
      `${options.selector} {\n${decls}\n}\n\n` +
      `@media (prefers-color-scheme: dark) {\n` +
      `  :root:not([data-theme='light']) {\n${decls.replace(/^/gm, '  ')}\n  }\n}\n`
    );
  },
});

/** Typed TS export — gives autocompletion and makes tokens usable in logic. */
StyleDictionary.registerFormat({
  name: 'ts/typed',
  format: ({ dictionary }) => {
    const entries = dictionary.allTokens
      .map(t => `  '${t.name}': '${String(t.value).replace(/'/g, "\\'")}',`)
      .join('\n');
    return (
      `// Generated by packages/tokens/build/build.mjs — do not edit.\n` +
      `export const tokens = {\n${entries}\n} as const;\n\n` +
      `export type TokenName = keyof typeof tokens;\n` +
      `export type TokenValue = (typeof tokens)[TokenName];\n\n` +
      `/** Resolve a token to its CSS custom-property reference. */\n` +
      `export const cssVar = (name: TokenName): string => \`var(--\${name})\`;\n`
    );
  },
});

const coreSources = [`${root}/src/core/**/*.json`];

/** Core tokens: emitted once, theme-independent. */
async function buildCore() {
  const sd = new StyleDictionary({
    source: coreSources,
    platforms: {
      css: {
        transformGroup: 'css',
        transforms: ['name/mrd-kebab'],
        buildPath: `${root}/dist/`,
        files: [
          {
            destination: '_core.css',
            format: 'css/themed',
            options: { selector: ':root', outputReferences: true },
          },
        ],
      },
      scss: {
        transformGroup: 'scss',
        transforms: ['name/mrd-kebab'],
        buildPath: `${root}/dist/`,
        files: [{ destination: '_core.scss', format: 'scss/variables' }],
      },
      json: {
        transformGroup: 'js',
        transforms: ['name/mrd-kebab'],
        buildPath: `${root}/dist/`,
        files: [{ destination: 'core.json', format: 'json/flat' }],
      },
    },
  });
  await sd.buildAllPlatforms();
}

/** Semantic tokens: one pass per theme, same token names, different values. */
async function buildTheme(theme) {
  const selector = theme === 'light' ? ":root, [data-theme='light']" : "[data-theme='dark']";
  const sd = new StyleDictionary({
    source: [
      ...coreSources,
      `${root}/src/semantic/${theme}.json`,
      `${root}/src/component/**/*.json`,
    ],
    platforms: {
      css: {
        transformGroup: 'css',
        transforms: ['name/mrd-kebab'],
        buildPath: `${root}/dist/`,
        files: [
          {
            destination: `_theme-${theme}.css`,
            format: 'css/themed',
            filter: t => t.path[0] === 'theme' || t.path[0] === 'component',
            options: { selector, outputReferences: false },
          },
        ],
      },
      ts: {
        transformGroup: 'js',
        transforms: ['name/mrd-kebab'],
        buildPath: `${root}/dist-src/`,
        files: [{ destination: `${theme}.ts`, format: 'ts/typed' }],
      },
      json: {
        transformGroup: 'js',
        transforms: ['name/mrd-kebab'],
        buildPath: `${root}/dist/`,
        files: [{ destination: `tokens.${theme}.json`, format: 'json/flat' }],
      },
    },
  });
  await sd.buildAllPlatforms();
}

async function main() {
  mkdirSync(`${root}/dist`, { recursive: true });
  mkdirSync(`${root}/dist-src`, { recursive: true });

  await buildCore();
  for (const theme of THEMES) await buildTheme(theme);

  /*
   * Single stylesheet consumers import: core first, then every theme layer.
   *
   * Concatenated, not `@import`ed. A CSS `@import` is discovered only after the
   * importing sheet has been parsed, so it serialises the requests — and these
   * are render-blocking custom properties that every component reads at first
   * paint. One file, one request.
   */
  const css =
    `/* Meridian design tokens. Generated by build.mjs — do not edit. */\n\n` +
    [`_core.css`, ...THEMES.map(t => `_theme-${t}.css`)]
      .map(file => readFileSync(`${root}/dist/${file}`, 'utf8'))
      .join('\n');
  writeFileSync(`${root}/dist/tokens.css`, css);

  writeFileSync(
    `${root}/dist/_tokens.scss`,
    `// Meridian design tokens. Generated — do not edit.\n@forward './core';\n`,
  );

  writeFileSync(
    `${root}/dist-src/index.ts`,
    `export { tokens as lightTokens, cssVar } from './light.js';\n` +
      `export { tokens as darkTokens } from './dark.js';\n` +
      `export type { TokenName, TokenValue } from './light.js';\n`,
  );

  console.log(`✔ tokens built — ${THEMES.length} themes`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
